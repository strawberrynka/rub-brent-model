"""Pin installed distributions, separating runtime and development dependencies."""

from importlib.metadata import distributions, distribution
from pathlib import Path
from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

ROOT = Path(__file__).resolve().parents[1]
runtime = set()


def include(name):
    key = canonicalize_name(name)
    if key in runtime:
        return
    runtime.add(key)
    package = distribution(name)
    for spec in package.requires or []:
        requirement = Requirement(spec)
        if not requirement.marker or requirement.marker.evaluate({"extra": ""}):
            include(requirement.name)


for name in (ROOT / "requirements.in").read_text().splitlines():
    if name and not name.startswith("#"):
        include(name)
installed = {canonicalize_name(d.metadata["Name"]): d.version for d in distributions()}
header = "# Tested with Python 3.12; generated by scripts/lock_environment.py\n"
(ROOT / "requirements.txt").write_text(
    header + "\n".join(f"{name}=={installed[name]}" for name in sorted(runtime)) + "\n", encoding="utf-8"
)
(ROOT / "requirements-dev.txt").write_text(
    "# Development environment; includes the runtime lock.\n-r requirements.txt\n"
    + "\n".join(
        f"{name}=={value}"
        for name, value in sorted(installed.items())
        if name not in runtime and name not in {"pip", "setuptools", "wheel"}
    )
    + "\n",
    encoding="utf-8",
)
